// Runtime derivation for the Phaser character lab: copies the registered (non-helper) animation sheets of a body into
// docs/assets/characters/<body>/ and writes docs/data/characters/<body>.json, the runtime definition the Phaser scene
// reads (states, rows, fps, clips, events, root motion, layer draw order, outfits, combo transitions).
// The sheets are byte-for-byte copies of the approved production outputs; nothing is re-rendered or resampled.
// Usage: node tools/export-character-runtime.mjs <body> [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const [bodyName, flag] = process.argv.slice(2);
if (!bodyName) { console.error('Usage: node tools/export-character-runtime.mjs <body> [--check]'); process.exit(2); }

const manifest = JSON.parse(fs.readFileSync(path.join(root, 'production/asset-manifest.json'), 'utf8'));
const plan = manifest.canonical.characterAnimationPlan;
const overlays = JSON.parse(fs.readFileSync(path.join(root, 'production/source/characters/rig', bodyName, 'overlays.json'), 'utf8'));
const animDir = path.join(root, 'production/source/characters/anim', bodyName);
const combo = JSON.parse(fs.readFileSync(path.join(animDir, 'combo.json'), 'utf8'));
const assetRoot = `assets/characters/${bodyName}`;

// output: map of docs-relative path -> Buffer | string
const files = new Map();
const states = {};
for (const [key, out] of Object.entries(plan.outputs)) {
  const [b, state] = key.split('/');
  if (b !== bodyName || out.helper) continue;
  const def = JSON.parse(fs.readFileSync(path.join(root, out.sheets, 'animation.json'), 'utf8'));
  const layers = {};
  for (const [name, file] of Object.entries(def.layers)) {
    const rel = `${assetRoot}/${state}/${file}`;
    files.set(rel, fs.readFileSync(path.join(root, out.sheets, file)));
    layers[name] = rel;
  }
  states[state] = {
    frames: def.frames, fps: def.fps, rows: def.sheetLayout.rows, status: def.status,
    rootMotion: def.rootMotion, layers,
    ...(def.clips ? { clips: def.clips } : {}),
    ...(def.events ? { events: def.events } : {})
  };
}

// contact shadow: the reference sheet's frames in reference order (S, SE, E, NE, N, NW, W, SW)
const shadow = overlays.groundLayers.find((g) => g.role === 'contact shadow');
files.set(`${assetRoot}/contact-shadow.png`, fs.readFileSync(path.join(root, shadow.file)));

const definition = {
  schema: 'astro-fighters-character-runtime/v1',
  body: bodyName,
  note: 'Generated by tools/export-character-runtime.mjs from the production outputs; do not edit by hand.',
  frameSize: [64, 64], pivot: [32, 63],
  facing: manifest.canonical.characterFacing,
  referenceFrameOrder: ['S', 'SE', 'E', 'NE', 'N', 'NW', 'W', 'SW'],
  contactShadow: `${assetRoot}/contact-shadow.png`,
  drawOrder: overlays.drawOrder,
  // layer slots in draw order (contact shadow below them); an outfit picks which layer fills each slot
  slots: [
    { slot: 'body', layers: ['body'] },
    { slot: 'clothing', layers: ['male-gi', 'male-blue-armor', 'male-red-armor'] },
    { slot: 'arms', layers: ['arms'] },
    { slot: 'armAccessories', layers: ['blue-armor-shoulders', 'red-armor-shoulders'] },
    { slot: 'hair', layers: ['fade-hair', 'long-hair', 'afro-hair'] },
    { slot: 'eyes', layers: ['brown-eyes', 'purple-eyes'] }
  ],
  outfits: {
    base: { clothing: null, armAccessories: null },
    gi: { clothing: 'male-gi', armAccessories: null },
    blueArmor: { clothing: 'male-blue-armor', armAccessories: 'blue-armor-shoulders' },
    redArmor: { clothing: 'male-red-armor', armAccessories: 'red-armor-shoulders' }
  },
  states,
  combo
};
files.set(`data/characters/${bodyName}.json`, JSON.stringify(definition, null, 2) + '\n');

const docs = path.join(root, 'docs');
if (flag === '--check') {
  const stale = [...files].filter(([rel, data]) => {
    const f = path.join(docs, rel);
    return !fs.existsSync(f) || !fs.readFileSync(f).equals(Buffer.isBuffer(data) ? data : Buffer.from(data));
  }).map(([rel]) => rel);
  if (stale.length) { console.error(`Character runtime export for ${bodyName} is stale (${stale.length} files, e.g. ${stale[0]}); rerun node tools/export-character-runtime.mjs ${bodyName}`); process.exit(1); }
  console.log(`Character runtime export for ${bodyName} is current (${files.size} files).`);
} else {
  for (const [rel, data] of files) { fs.mkdirSync(path.dirname(path.join(docs, rel)), { recursive: true }); fs.writeFileSync(path.join(docs, rel), data); }
  console.log(`Wrote ${files.size} files under docs/ (${Object.keys(states).join(', ')}).`);
}
