// Writes docs/ABILITY_ANIMATION_COVERAGE.md: every ability in the hex testbed, the rig animation it plays
// (web/af-anim-map-v3.js), and the frame sets still to author. Run after changing the ability table,
// the kits, or the rig: node tools/report-ability-animations.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
globalThis.window = globalThis;
for (const m of ['af-core.js', 'af-dc-model-v3.js', 'af-core-v3-patch.js', 'af-ui-v3.js', 'af-anim-map-v3.js', 'af-sprites-v3.js']) require(path.join(root, 'web', m));
const { AF, AFAnimMap, AFSprites } = globalThis;
const rig = JSON.parse(fs.readFileSync(path.join(root, 'web/characters/male.json'), 'utf8'));

// every ability, with who can use it
const abilities = new Map();
const add = (ab, source, humanoid) => {
  const key = `${ab.pos?.scope || ab.group}|${ab.name}`;
  let row = abilities.get(key);
  if (!row) { row = { ab, sources: new Set(), humanoid: false }; abilities.set(key, row); }
  row.sources.add(source); row.humanoid ||= humanoid;
};
const kitOf = (ab) => {
  const scope = ab.pos?.scope || '';
  if (scope.startsWith('Martial|') || scope.startsWith('Weapon|')) return scope.replace('|', ': ');
  return ab.group;
};
for (const weapon of Object.keys(AF.WEAPONS)) {
  const all = AF.buildLoadout({ unlockAll: true, martials: Object.keys(AF.MARTIAL), weapon, learnedMedical: ['Palm Healing', 'Cellular Activation'] });
  for (const ab of all) add(ab, `player · ${kitOf(ab)}`, true);
}
for (const key of AF.ENEMY_KEYS) {
  const E = AF.ENEMIES[key];
  for (const ab of AF.enemyLoadout(key)) add(ab, E.name, AFSprites.isHumanoid({ glyph: E.glyph }));
}

const rows = [...abilities.values()].map(({ ab, sources, humanoid }) => {
  const m = AFAnimMap.forAbility(ab);
  for (const [state, clip] of m.play) {
    if (!rig.states[state]) throw new Error(`${ab.name}: rig has no state ${state}`);
    if (clip && !rig.states[state].clips?.[clip]) throw new Error(`${ab.name}: rig has no clip ${state}/${clip}`);
  }
  const playable = m.play.map(([s, c]) => c || s).join(' → ') || (m.fit === 'missing' && ab.dmg && ab.dmg !== 'None' && ab.atk !== 'Melee' ? '(bolt only)' : '—');
  return { name: ab.name, group: ab.group, kit: kitOf(ab), sources: [...sources], humanoid, fit: m.fit, need: m.need, playable, weapon: m.weapon || '' };
}).sort((a, b) => a.group.localeCompare(b.group) || a.name.localeCompare(b.name));

const rigged = rows.filter((r) => r.humanoid), glyphOnly = rows.filter((r) => !r.humanoid);
const count = (fit) => rigged.filter((r) => r.fit === fit).length;
const needs = new Map();
for (const r of rigged) if (r.need) { if (!needs.has(r.need)) needs.set(r.need, []); needs.get(r.need).push(r); }
const esc = (s) => String(s).replace(/\|/g, '\\|');

let md = `# Ability animation coverage

Generated by \`tools/report-ability-animations.mjs\` from \`web/af-anim-map-v3.js\` and the imported rig (\`web/characters/male.json\`, playtest ${rig.source?.commit || '?'}). Do not edit by hand.

The hex testbed has ${rows.length} abilities. ${rigged.length} can be used by a fighter drawn with the rig: the player, allies, and the human opponents. The other ${glyphOnly.length} belong only to beasts and undead, which stay glyph tokens.

| Fit | Abilities | Meaning |
| --- | ---: | --- |
| exact | ${count('exact')} | an authored animation is this technique |
| stand-in | ${count('standIn')} | a nearby authored animation plays until the technique's own frames exist |
| missing | ${count('missing')} | nothing authored fits; ranged damage draws a bolt, everything else plays no motion |

## How a landed hit reads

The defender's poise at the moment of the hit picks the reaction. A fighter that still had poise takes the blow on the guard, so it plays **block**. The hit that empties poise plays the **guard-break** stagger. Only hits on a fighter already at 0 poise play the **hit recoil**. A downing blow always plays the recoil, then fades. An evade plays the **weave**, and a parry plays the **block**.

## Frame sets still needed

Ordered by how many abilities wait on each set. "Stand-in" abilities already animate with a nearby motion.

| Frame set | Abilities | Waiting (fit) |
| --- | ---: | --- |
`;
for (const [need, list] of [...needs.entries()].sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]))) {
  md += `| ${esc(need)} | ${list.length} | ${list.map((r) => `${esc(r.name)}${r.fit === 'standIn' ? ' (stand-in)' : ''}`).join(', ')} |\n`;
}
md += `
## Every rigged ability

| Ability | Kit | Plays | Fit | Needs |
| --- | --- | --- | --- | --- |
`;
for (const r of rigged) md += `| ${esc(r.name)} | ${esc(r.kit)} | ${esc(r.playable)}${r.weapon ? ` (${r.weapon})` : ''} | ${r.fit === 'standIn' ? 'stand-in' : r.fit} | ${esc(r.need)} |\n`;
md += `
## Beast and undead abilities (no rig)

${glyphOnly.map((r) => `${r.name} (${r.sources.join(', ')})`).join(' · ')}
`;

const out = path.join(root, 'docs/ABILITY_ANIMATION_COVERAGE.md');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== md) { console.error('docs/ABILITY_ANIMATION_COVERAGE.md is stale: run node tools/report-ability-animations.mjs'); process.exit(1); }
  console.log('ability animation coverage is current');
} else {
  fs.writeFileSync(out, md);
  console.log(`wrote docs/ABILITY_ANIMATION_COVERAGE.md: ${rigged.length} rigged (${count('exact')} exact, ${count('standIn')} stand-in, ${count('missing')} missing), ${needs.size} frame sets needed`);
}
